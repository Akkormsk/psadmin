"""Соответствие «наши нормализованные параметры» → «поля формы FSPrint».

Пока здесь ровно одно однозначное соответствие — количество тиража.
Всё остальное (материалы, ламинация, вырубка, тиснение — main1*/main2*)
специфично для КОНКРЕТНОГО product_id, и мы пока знаем набор полей
только для одного примера (packet), без знания допустимых значений.
Подключать сюда новые соответствия можно только по одному, после того
как для конкретного продукта разобран реальный ответ калькулятора —
не раньше (см. docs/backlog/fsprint-adapter.md)."""


def apply_quantity(payload: dict, quantity: int) -> dict:
    """quantity → tiraj. Единственное поле, чей смысл не требует знания
    внутренних FSPrint-enum — просто число тиража."""
    return {**payload, "tiraj": str(int(quantity))}
